function record(config) {
  const institutionName = config.institutionName
  return {
    id: config.id,
    reference: config.reference,
    institutionId: config.institutionId,
    institutionName,
    bank: config.bank,
    branch: config.branch,
    amount: config.amount,
    issueDate: config.issueDate,
    maturityDate: config.maturityDate,
    beneficiary: config.beneficiary ?? 'All India Council for Technical Education',
    holder: config.holder ?? institutionName,
    purpose: config.purpose,
    lifecycleStatus: config.lifecycleStatus,
    verificationStatus: config.verificationStatus,
    integrityStatus: config.integrityStatus ?? 'clear',
    reviewerId: config.reviewerId ?? 'u-rev1',
    submittedById: config.submittedById ?? 'u-officer1',
    submittedBy: config.submittedBy ?? 'Rohan Deshpande',
    createdAt: config.createdAt ?? iso(config.issueOffset + 2, 11),
    updatedAt: config.updatedAt ?? iso(config.updatedAtOffset ?? -3, 15),
    extractionStatus: config.extractionStatus ?? 'extracted',
    extracted: config.extracted ?? {
      reference: config.reference,
      amount: config.amount,
      issueDate: config.issueDate,
      maturityDate: config.maturityDate,
      beneficiary: config.beneficiary ?? 'All India Council for Technical Education',
      confidence: 0.94,
    },
    document: config.document ?? {
      id: `doc-${config.id}`,
      name: `${config.reference}_FDR_scan.pdf`,
      type: 'application/pdf',
      size: 184320,
      source: 'seeded',
    },
    approval: config.approval ?? { required: false, approved: false },
    notes: config.notes ?? '',
    tags: config.tags ?? [],
  }
}

function base(institutionId, institutionName, officerId, officerName) {
  return { institutionId, institutionName, submittedById: officerId, submittedBy: officerName }
}

