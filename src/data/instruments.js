/**
 * SYNTHETIC DEMO DATA. Banks and institutions are fictional. Dates are
 * generated relative to the current day so deadline scenarios stay meaningful.
 */
function iso(offsetDays, hour = 10) {
  const date = startOfDay(addDays(new Date(), offsetDays))
  date.setHours(hour, 0, 0, 0)
  return formatISO(date)
}

function dateOnly(offsetDays) {
  return formatISO(startOfDay(addDays(new Date(), offsetDays)), { representation: 'date' })
}

